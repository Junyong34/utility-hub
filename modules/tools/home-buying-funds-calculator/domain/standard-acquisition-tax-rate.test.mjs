import assert from 'node:assert/strict';
import test from 'node:test';

import { calculateStandardHomeAcquisitionTax } from '../public.ts';

// 「지방세법」 제11조제1항제8호 나목(law.go.kr, MST=282559, JO=001100, 조문시행일자
// 2026-01-01)의 6억 초과 9억 이하 보간세율 구간을 값 단위로 고정한다.
//
//   세율 = (취득당시가액 × 2 / 3억원 − 3) × 1/100
//   (소수점 다섯째자리에서 반올림하여 넷째자리까지 계산)
//
// 아래 기대값은 전부 위 산식을 손으로 계산해 유도한 것이며, 코드가 실제로 반환하는 값을
// 그대로 베낀 것이 아니다(각 케이스 옆에 유도 과정을 남긴다). 이 구간을 부동소수점
// (`salePrice / 300_000_000`)으로 계산하면 0.01005 같은 유한소수가 이진수로 정확히
// 표현되지 않아 정확히 .5에서 반올림해야 하는 지점에서 한 자리 낮게 반올림되는 사례가
// 실측으로 확인됐다 — 특히 600,750,000원(1.005% → 반올림 1.01%가 정답)이 대표 사례다.

test('6억 초과 9억 이하 구간의 세율이 정확히 .5에서 반올림되는 tie 케이스를 올바르게 처리한다', () => {
  // 600,750,000원: raw = (600,750,000×2/300,000,000 − 3) = 4.005 − 3 = 1.005
  //   → 세율 = 1.005% = 0.01005, 5번째 소수자리가 정확히 5 → 반올림(올림) → 0.0101 (1.01%)
  //   → 취득세 = 600,750,000 × 0.0101 = 600,750,000 × 101 / 10000
  //            = 60,675,750,000 / 10000 = 6,067,575원 (나누어떨어짐, 절사 불필요)
  assert.equal(calculateStandardHomeAcquisitionTax(600_750_000), 6_067_575);
});

test('6억 초과 9억 이하 구간의 다른 tie 케이스들도 정확히 반올림된다', () => {
  // 720,750,000원: raw = (720,750,000×2/300,000,000 − 3) = 4.805 − 3 = 1.805
  //   → 세율 = 1.805% = 0.01805, 5번째 소수자리 5 → 반올림 → 0.0181 (1.81%)
  //   → 취득세 = 720,750,000 × 181 / 10000 = 130,455,750,000 / 10000 = 13,045,575원
  assert.equal(calculateStandardHomeAcquisitionTax(720_750_000), 13_045_575);

  // 750,750,000원: raw = (750,750,000×2/300,000,000 − 3) = 5.005 − 3 = 2.005
  //   → 세율 = 2.005% = 0.02005, 5번째 소수자리 5 → 반올림 → 0.0201 (2.01%)
  //   → 취득세 = 750,750,000 × 201 / 10000 = 150,900,750,000 / 10000 = 15,090,075원
  assert.equal(calculateStandardHomeAcquisitionTax(750_750_000), 15_090_075);
});

test('8억 주택의 산출세액은 2.33%로 반올림된 세율로 계산된다', () => {
  // 800,000,000원: raw = (800,000,000×2/300,000,000 − 3) = 5.3333... − 3 = 2.3333...
  //   → 세율 = 2.3333...%, 5번째 소수자리는 3(0.023333...) → 반올림 없이 내림 → 0.0233 (2.33%)
  //   → 취득세 = 800,000,000 × 233 / 10000 = 186,400,000,000 / 10000 = 18,640,000원
  assert.equal(calculateStandardHomeAcquisitionTax(800_000_000), 18_640_000);
});

test('6억원 구간 경계(가목/나목)는 연속적으로 이어진다', () => {
  // 가목(6억 이하): 6억 × 1% = 6,000,000원 (반올림 대상 아님, 정확히 1%)
  assert.equal(calculateStandardHomeAcquisitionTax(600_000_000), 6_000_000);
  // 나목 첫 원(6억+1원): raw = (600,000,001×2/300,000,000 − 3) ≈ 1.0000000067
  //   → 세율 ≈ 1.0000000067%, 5번째 소수자리 0 → 반올림 없이 0.0100 (1.00%)
  //   → 취득세 = floor(600,000,001 × 0.01) = floor(6,000,000.01) = 6,000,000원
  //   (가목 값과 연속 — 경계에서 세액이 튀지 않는다)
  assert.equal(calculateStandardHomeAcquisitionTax(600_000_001), 6_000_000);
});

test('9억원 구간 경계(나목/다목)는 연속적으로 이어진다', () => {
  // 나목 마지막 원(9억): raw = (900,000,000×2/300,000,000 − 3) = 6 − 3 = 3, 정확히 3.00%
  //   → 취득세 = 900,000,000 × 3% = 27,000,000원
  assert.equal(calculateStandardHomeAcquisitionTax(900_000_000), 27_000_000);
  // 다목 첫 원(9억+1원): 9억 초과는 일괄 3% → floor(900,000,001 × 0.03)
  //   = floor(27,000,000.03) = 27,000,000원 (나목 값과 연속)
  assert.equal(calculateStandardHomeAcquisitionTax(900_000_001), 27_000_000);
});
